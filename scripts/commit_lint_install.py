#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
commit_lint_install.py — Git commit-msg Hook 安装管理脚本
============================================================

用途
----
管理 .git/hooks/commit-msg 钩子的安装/卸载/状态检查，钩子调用
commit_lint.py 在提交时校验 commit message 格式。

技术约束
--------
* 仅使用 Python 标准库（os/sys/json/argparse/shutil/datetime），无 pip 依赖。
* 兼容 Python >= 3.8。
* 输出 JSON 格式，对齐 git_backup_tidy.py 风格。
* hook 内容用 sh 兼容写法（#!/bin/sh），Windows + macOS + Linux 通用。

安全设计
--------
* install 前检测是否已存在 hook，存在且非框架生成则备份为 commit-msg.bak.{timestamp}
* uninstall 时恢复备份或删除（仅删除框架生成的 hook，不删用户自定义 hook）
* status 报告 hook 是否安装 + 是否为框架生成

================================================================================
运行方式
================================================================================
  python commit_lint_install.py install     # 安装 hook
  python commit_lint_install.py uninstall   # 卸载 hook
  python commit_lint_install.py status      # 检查 hook 状态
"""

import argparse
import json
import os
import shutil
import sys
from datetime import datetime

# ===========================================================================
# 常量
# ===========================================================================

# 框架标识（用于识别 hook 是否为框架生成）
HOOK_MARKER = '# riji-skill commit-msg hook (auto-generated by commit_lint_install.py)'

# hook 内容模板（sh 兼容写法，Windows Git Bash 也能跑）
HOOK_TEMPLATE = """#!/bin/sh
# riji-skill commit-msg hook (auto-generated by commit_lint_install.py)
# 校验 commit message 是否符合 Conventional Commits + 框架规范
# 卸载请运行: python scripts/commit_lint_install.py uninstall
PYTHON="${PYTHON:-python}"
SCRIPT_DIR="$(cd "$(dirname "$0")/../../scripts" && pwd)"
"$PYTHON" "$SCRIPT_DIR/commit_lint.py" lint-file "$1"
exit $?
"""

# ===========================================================================
# 辅助函数
# ===========================================================================

def find_git_root(start_path=None):
    """从指定路径向上查找 .git 目录，返回 git 仓库根路径。

    Args:
        start_path: 起始查找路径，默认当前目录

    Returns:
        str: git 根路径，找不到返回 None
    """
    if start_path is None:
        start_path = os.getcwd()

    current = os.path.abspath(start_path)
    while True:
        git_dir = os.path.join(current, '.git')
        if os.path.isdir(git_dir):
            return current
        parent = os.path.dirname(current)
        if parent == current:
            return None
        current = parent


def get_hook_path(git_root):
    """获取 commit-msg hook 文件路径。"""
    return os.path.join(git_root, '.git', 'hooks', 'commit-msg')


def is_framework_hook(hook_path):
    """检测 hook 是否为框架生成。"""
    if not os.path.isfile(hook_path):
        return False
    try:
        with open(hook_path, 'r', encoding='utf-8') as f:
            content = f.read()
        return HOOK_MARKER in content
    except IOError:
        return False


def ensure_hooks_dir(git_root):
    """确保 .git/hooks/ 目录存在。"""
    hooks_dir = os.path.join(git_root, '.git', 'hooks')
    if not os.path.isdir(hooks_dir):
        os.makedirs(hooks_dir, exist_ok=True)
    return hooks_dir


# ===========================================================================
# 命令实现
# ===========================================================================

def cmd_install(args):
    """install 子命令：安装 commit-msg hook。"""
    git_root = find_git_root(args.repo if hasattr(args, 'repo') else None)
    if not git_root:
        result = {
            'installed': False,
            'error': 'Not a git repository (no .git directory found)',
            'git_root': None,
        }
        print(json.dumps(result, ensure_ascii=False, indent=2) if args.json else
              f'[ERROR] {result["error"]}')
        return 2

    hook_path = get_hook_path(git_root)
    ensure_hooks_dir(git_root)

    # 已存在且为框架生成 → 幂等跳过
    if os.path.isfile(hook_path) and is_framework_hook(hook_path):
        result = {
            'installed': True,
            'action': 'noop',
            'message': 'Hook already installed (framework-generated)',
            'git_root': git_root,
            'hook_path': hook_path,
        }
        print(json.dumps(result, ensure_ascii=False, indent=2) if args.json else
              f'[OK] {result["message"]}')
        return 0

    # 已存在且非框架生成 → 备份
    backup_path = None
    if os.path.isfile(hook_path) and not is_framework_hook(hook_path):
        timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
        backup_path = hook_path + f'.bak.{timestamp}'
        shutil.copy2(hook_path, backup_path)

    # 写入 hook
    try:
        with open(hook_path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(HOOK_TEMPLATE)
    except IOError as e:
        result = {
            'installed': False,
            'error': f'Failed to write hook: {e}',
            'git_root': git_root,
            'hook_path': hook_path,
        }
        print(json.dumps(result, ensure_ascii=False, indent=2) if args.json else
              f'[ERROR] {result["error"]}')
        return 2

    # 设置可执行权限（Unix；Windows 不需要）
    if os.name != 'nt':
        try:
            os.chmod(hook_path, 0o755)
        except OSError:
            pass  # 权限设置失败不阻断

    result = {
        'installed': True,
        'action': 'backup' if backup_path else 'install',
        'message': 'Hook installed successfully',
        'git_root': git_root,
        'hook_path': hook_path,
        'backup_path': backup_path,
    }
    print(json.dumps(result, ensure_ascii=False, indent=2) if args.json else
          f'[OK] {result["message"]}' +
          (f' (backed up: {backup_path})' if backup_path else ''))
    return 0


def cmd_uninstall(args):
    """uninstall 子命令：卸载 commit-msg hook。"""
    git_root = find_git_root(args.repo if hasattr(args, 'repo') else None)
    if not git_root:
        result = {
            'uninstalled': False,
            'error': 'Not a git repository (no .git directory found)',
            'git_root': None,
        }
        print(json.dumps(result, ensure_ascii=False, indent=2) if args.json else
              f'[ERROR] {result["error"]}')
        return 2

    hook_path = get_hook_path(git_root)

    if not os.path.isfile(hook_path):
        result = {
            'uninstalled': True,
            'action': 'noop',
            'message': 'No hook to uninstall',
            'git_root': git_root,
        }
        print(json.dumps(result, ensure_ascii=False, indent=2) if args.json else
              f'[OK] {result["message"]}')
        return 0

    # 框架生成的 hook → 删除 + 恢复备份
    if is_framework_hook(hook_path):
        # 查找备份
        hooks_dir = os.path.dirname(hook_path)
        backups = sorted([
            f for f in os.listdir(hooks_dir)
            if f.startswith('commit-msg.bak.')
        ]) if os.path.isdir(hooks_dir) else []

        restored_from = None
        if backups:
            latest_backup = os.path.join(hooks_dir, backups[-1])
            shutil.move(latest_backup, hook_path)
            restored_from = latest_backup
            action = 'restore'
        else:
            os.remove(hook_path)
            action = 'remove'

        result = {
            'uninstalled': True,
            'action': action,
            'message': 'Hook uninstalled successfully',
            'git_root': git_root,
            'hook_path': hook_path,
            'restored_from': restored_from,
        }
        print(json.dumps(result, ensure_ascii=False, indent=2) if args.json else
              f'[OK] {result["message"]}' +
              (f' (restored from: {restored_from})' if restored_from else ''))
        return 0

    # 非框架生成的 hook → 不删除，提示用户
    result = {
        'uninstalled': False,
        'action': 'skip',
        'message': 'Hook is not framework-generated, skipping. '
                   'Remove manually if needed: ' + hook_path,
        'git_root': git_root,
        'hook_path': hook_path,
    }
    print(json.dumps(result, ensure_ascii=False, indent=2) if args.json else
          f'[WARN] {result["message"]}')
    return 1


def cmd_status(args):
    """status 子命令：检查 hook 状态。"""
    git_root = find_git_root(args.repo if hasattr(args, 'repo') else None)
    if not git_root:
        result = {
            'is_git_repo': False,
            'installed': False,
            'framework_generated': False,
            'git_root': None,
        }
        print(json.dumps(result, ensure_ascii=False, indent=2) if args.json else
              '[INFO] Not a git repository')
        return 0

    hook_path = get_hook_path(git_root)
    installed = os.path.isfile(hook_path)
    framework_gen = is_framework_hook(hook_path) if installed else False

    # 查找备份
    hooks_dir = os.path.dirname(hook_path) if installed else os.path.join(git_root, '.git', 'hooks')
    backups = []
    if os.path.isdir(hooks_dir):
        backups = sorted([
            f for f in os.listdir(hooks_dir)
            if f.startswith('commit-msg.bak.')
        ])

    result = {
        'is_git_repo': True,
        'installed': installed,
        'framework_generated': framework_gen,
        'git_root': git_root,
        'hook_path': hook_path,
        'backups': backups,
    }
    print(json.dumps(result, ensure_ascii=False, indent=2) if args.json else
          _format_status_human(result))
    return 0


def _format_status_human(r):
    """status 人类可读格式。"""
    lines = []
    lines.append(f"Git repo: {r['git_root']}")
    lines.append(f"Hook installed: {'Yes' if r['installed'] else 'No'}")
    if r['installed']:
        lines.append(f"Framework-generated: {'Yes' if r['framework_generated'] else 'No (user custom)'}")
        lines.append(f"Hook path: {r['hook_path']}")
    if r['backups']:
        lines.append(f"Backups: {len(r['backups'])} file(s)")
        for b in r['backups']:
            lines.append(f"  - {b}")
    return '\n'.join(lines)


# ===========================================================================
# CLI 入口
# ===========================================================================

def main():
    parser = argparse.ArgumentParser(
        description='Git commit-msg Hook 安装管理脚本（riji-skill 框架）',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
功能：
  install   — 安装 commit-msg hook（调用 commit_lint.py 校验）
  uninstall — 卸载 hook（恢复备份或删除）
  status    — 检查 hook 状态

安全：
  * 已存在用户自定义 hook → 自动备份为 commit-msg.bak.{timestamp}
  * uninstall 只删除框架生成的 hook，不删用户自定义 hook
        """,
    )
    subparsers = parser.add_subparsers(dest='command', help='子命令')

    # install
    p_install = subparsers.add_parser('install', help='安装 commit-msg hook')
    p_install.add_argument('--repo', help='git 仓库路径（默认自动检测）')
    p_install.add_argument('--json', action='store_true', help='JSON 输出')
    p_install.set_defaults(func=cmd_install)

    # uninstall
    p_uninstall = subparsers.add_parser('uninstall', help='卸载 commit-msg hook')
    p_uninstall.add_argument('--repo', help='git 仓库路径（默认自动检测）')
    p_uninstall.add_argument('--json', action='store_true', help='JSON 输出')
    p_uninstall.set_defaults(func=cmd_uninstall)

    # status
    p_status = subparsers.add_parser('status', help='检查 hook 状态')
    p_status.add_argument('--repo', help='git 仓库路径（默认自动检测）')
    p_status.add_argument('--json', action='store_true', help='JSON 输出')
    p_status.set_defaults(func=cmd_status)

    args = parser.parse_args()
    if not args.command:
        parser.print_help()
        return 1

    return args.func(args)


if __name__ == '__main__':
    sys.exit(main())
